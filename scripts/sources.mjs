// Regenerates the citation list at the end of RULES.md from src/core/sources.js.
// `node scripts/sources.mjs --check` exits with an error instead when the list
// is out of date (the test suite runs the same comparison).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- sources:start: generated by `npm run sources` from src/core/sources.js; do not edit by hand -->';
const END = '<!-- sources:end -->';

export function loadSources() {
  const context = { globalThis: {} };
  context.globalThis = context;
  vm.createContext(context);
  vm.runInContext(readFileSync(join(ROOT, 'src/core/sources.js'), 'utf8'), context);
  return context.HeaderAnalyzer.sources;
}

export function citationBlock(sources) {
  const ids = [...sources.ids].sort();
  const list = ids.map((id) => {
    const c = sources.cite(id);
    return `- \`${id}\`: [${c.title}][${id}]: “${c.quote}”`;
  });
  const refs = ids.map((id) => `[${id}]: ${sources.cite(id).url}`);
  return [START, '', ...list, '', ...refs, '', END].join('\n');
}

function render(rules, block) {
  const a = rules.indexOf(START);
  const z = rules.indexOf(END);
  if (a === -1 || z === -1) return `${rules.trimEnd()}\n\n${block}\n`;
  return rules.slice(0, a) + block + rules.slice(z + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = join(ROOT, 'RULES.md');
  const rules = readFileSync(path, 'utf8');
  const next = render(rules, citationBlock(loadSources()));
  if (process.argv.includes('--check')) {
    if (next !== rules) {
      console.error('RULES.md citations are out of date: run npm run sources');
      process.exit(1);
    }
  } else if (next !== rules) {
    writeFileSync(path, next);
    console.log('RULES.md citations updated');
  } else {
    console.log('RULES.md citations already up to date');
  }
}

export { START, END, render };
